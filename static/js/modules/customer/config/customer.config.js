(function(root){
  'use strict';

  var Modules = root.BlossomModules = root.BlossomModules || {};

  function sanitizeString(value){
    return String(value == null ? '' : value).trim();
  }

  function sanitizeQuantity(value){
    if(value == null || String(value).trim() === '') return 0;
    var parsed = parseInt(value, 10);
    return isFinite(parsed) && parsed >= 0 ? parsed : 0;
  }

  function normalizeCodeSeed(seed){
    var base = sanitizeString(seed || 'ASSOC').toUpperCase();
    var normalized = base.replace(/[^A-Z0-9]+/g, '_').replace(/^_+|_+$/g, '');
    return (normalized || 'ASSOC').slice(0, 60);
  }

  function isAutoGeneratedCustomerCode(code, memberName){
    var value = sanitizeString(code).toUpperCase();
    var base = normalizeCodeSeed(memberName);
    var suffix = '';
    if(!value) return false;
    if(value === base) return true;
    if(value.indexOf(base + '_') !== 0) return false;
    suffix = value.slice(base.length + 1);
    return /^[0-9]+$/.test(suffix);
  }

  function textCell(row, helpers, key){
    return helpers.escape(helpers.text(row[key]));
  }

  function detailLink(row, helpers){
    var label = helpers.text(row.member_name || row.customer_name);
    var href = row.public_id ? '/b/' + encodeURIComponent(row.public_id) : (root.__CAT_CUSTOMER_CLIENT1_DETAIL_URL || '/b/cat_customer_client1_detail');
    if(label === '-') return helpers.escape(label);
    return '<a href="' + helpers.escape(href) + '" class="work-name-link customer-detail-link" data-id="' + helpers.escape(row.id) + '" data-public-id="' + helpers.escape(row.public_id || '') + '" data-name="' + helpers.escape(row.member_name || row.customer_name || '') + '" data-address="' + helpers.escape(row.address || '') + '" data-manager-count="' + helpers.escape(row.manager_count || 0) + '" data-line-qty="' + helpers.escape(row.line_qty || 0) + '" data-note="' + helpers.escape(row.note || '') + '" title="고객 상세로 이동">' + helpers.escape(label) + '</a>';
  }

  Modules.customerConfig = {
    id: 'customer',
    pageClass: 'customer-page',
    showHeader: false,
    rowKey: 'id',
    title: '고객 관리',
    description: '고객을 관리합니다.',
    listTitle: '고객',
    pageSize: 10,
    exportName: '고객목록',
    actions: {
      create: true,
      update: true,
      delete: true,
      bulk: true,
      export: true,
      statistics: true
    },
    columns: [
      { key: 'member_name', label: '고객', searchable: true, render: detailLink },
      { key: 'customer_code', label: '고객코드', searchable: true, render: function(row, helpers){ return textCell(row, helpers, 'customer_code'); } },
      { key: 'phone', label: '대표번호', searchable: true, render: function(row, helpers){ return textCell(row, helpers, 'phone'); } },
      { key: 'address', label: '주소', searchable: true, render: function(row, helpers){ return textCell(row, helpers, 'address'); } },
      { key: 'line_qty', label: '회선(수량)', searchable: false, render: function(row, helpers){ return helpers.escape(String(row.line_qty || 0)); } },
      { key: 'note', label: '비고', searchable: true, hidden: true, render: function(row, helpers){ return textCell(row, helpers, 'note'); } }
    ],
    normalizeRows: function(rows){
      return (Array.isArray(rows) ? rows : []).map(function(row){
        row = row || {};
        var memberName = sanitizeString(row.member_name || row.customer_name || row.associate_name);
        var rawCode = sanitizeString(row.customer_code || row.associate_code || row.member_code || '');
        return {
          id: Number(row.id),
          public_id: row.public_id || '',
          member_name: memberName,
          customer_name: memberName,
          customer_code: isAutoGeneratedCustomerCode(rawCode, memberName) ? '' : rawCode,
          phone: sanitizeString(row.phone || ''),
          address: sanitizeString(row.address),
          manager_count: sanitizeQuantity(row.manager_count),
          line_qty: sanitizeQuantity(row.line_qty != null ? row.line_qty : row.line_count),
          note: sanitizeString(row.note != null ? row.note : row.remark)
        };
      }).filter(function(row){ return isFinite(row.id); });
    },
    openStats: function(rows){
      if(!root.blsStats) return;
      var body = document.getElementById('system-stats-body');
      if(body) body.innerHTML = '';
      root.blsStats.defineSections({
        'stats-software': '고객',
        'stats-versions': '고객코드',
        'stats-check': '회선 수량'
      });
      root.blsStats.renderCard('stats-software', '고객', root.blsStats.countBy(rows, 'member_name'));
      root.blsStats.renderCard('stats-versions', '고객코드', root.blsStats.countBy(rows, 'customer_code'));
      root.blsStats.renderCard('stats-check', '회선 수량', root.blsStats.countBy(rows, 'line_qty'));
      root.blsStats.open('system-stats-modal');
    }
  };

})(window);